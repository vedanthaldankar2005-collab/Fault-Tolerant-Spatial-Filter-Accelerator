module spatial_filter #(
    parameter IMAGE_WIDTH = 8
)(
    input  logic        clk,
    input  logic        rst,

    input  logic [7:0]  pixel_in,
    input  logic        pixel_valid,

    input  logic signed [7:0] kernel0,
    input  logic signed [7:0] kernel1,
    input  logic signed [7:0] kernel2,
    input  logic signed [7:0] kernel3,
    input  logic signed [7:0] kernel4,
    input  logic signed [7:0] kernel5,
    input  logic signed [7:0] kernel6,
    input  logic signed [7:0] kernel7,
    input  logic signed [7:0] kernel8,

    output logic signed [19:0] result,
    output logic               result_valid,

    // Hybrid fault-detection output
    output logic               residue_error
);

    // ============================================================
    // PRIMARY 3x3 WINDOW
    //
    // This window feeds the actual MAC datapath.
    // ============================================================

    logic [7:0] window0;
    logic [7:0] window1;
    logic [7:0] window2;
    logic [7:0] window3;
    logic [7:0] window4;
    logic [7:0] window5;
    logic [7:0] window6;
    logic [7:0] window7;
    logic [7:0] window8;

    logic window_valid;

    // ============================================================
    // INDEPENDENT CHECKER WINDOW
    //
    // This is generated by a SECOND window generator.
    //
    // It does not use the primary window signals.
    // Therefore a fault injected into the primary window path
    // can be detected by the residue checker.
    // ============================================================

    logic [7:0] check_window0;
    logic [7:0] check_window1;
    logic [7:0] check_window2;
    logic [7:0] check_window3;
    logic [7:0] check_window4;
    logic [7:0] check_window5;
    logic [7:0] check_window6;
    logic [7:0] check_window7;
    logic [7:0] check_window8;

    logic check_window_valid;

    // ============================================================
    // MAC RESULT
    // ============================================================

    logic signed [19:0] mac_result;

    // ============================================================
    // RESIDUE CHECKER RESULT
    // ============================================================

    logic residue_check_result;

    // ============================================================
    // PRIMARY WINDOW GENERATOR
    //
    // Main datapath window.
    // ============================================================

    window_generator #(
        .IMAGE_WIDTH(IMAGE_WIDTH)
    ) window_gen (
        .clk          (clk),
        .rst          (rst),

        .pixel_in     (pixel_in),
        .pixel_valid  (pixel_valid),

        .window0      (window0),
        .window1      (window1),
        .window2      (window2),
        .window3      (window3),
        .window4      (window4),
        .window5      (window5),
        .window6      (window6),
        .window7      (window7),
        .window8      (window8),

        .window_valid (window_valid)
    );

    // ============================================================
    // INDEPENDENT CHECKER WINDOW GENERATOR
    //
    // Separate instance and separate internal state.
    // ============================================================

    window_generator #(
        .IMAGE_WIDTH(IMAGE_WIDTH)
    ) checker_window_gen (
        .clk          (clk),
        .rst          (rst),

        .pixel_in     (pixel_in),
        .pixel_valid  (pixel_valid),

        .window0      (check_window0),
        .window1      (check_window1),
        .window2      (check_window2),
        .window3      (check_window3),
        .window4      (check_window4),
        .window5      (check_window5),
        .window6      (check_window6),
        .window7      (check_window7),
        .window8      (check_window8),

        .window_valid (check_window_valid)
    );

    // ============================================================
    // MAIN MAC
    //
    // Uses ONLY the primary window.
    // ============================================================

    mac mac_unit (
        .pixel0  ($signed(window0)),
        .pixel1  ($signed(window1)),
        .pixel2  ($signed(window2)),
        .pixel3  ($signed(window3)),
        .pixel4  ($signed(window4)),
        .pixel5  ($signed(window5)),
        .pixel6  ($signed(window6)),
        .pixel7  ($signed(window7)),
        .pixel8  ($signed(window8)),

        .kernel0 (kernel0),
        .kernel1 (kernel1),
        .kernel2 (kernel2),
        .kernel3 (kernel3),
        .kernel4 (kernel4),
        .kernel5 (kernel5),
        .kernel6 (kernel6),
        .kernel7 (kernel7),
        .kernel8 (kernel8),

        .result  (mac_result)
    );

    // ============================================================
    // INDEPENDENT RESIDUE ARITHMETIC CHECKER
    //
    // Expected result is calculated from the INDEPENDENT
    // checker window.
    //
    // Actual result comes from the MAIN MAC.
    //
    // Therefore:
    //
    // correct primary window + correct MAC
    //      -> residue matches
    //
    // faulty primary window
    //      -> residue mismatch
    //
    // faulty MAC
    //      -> residue mismatch
    // ============================================================

    residue_check #(
        .WIDTH  (20),
        .MODULUS(31)
    ) residue_checker (

        .pixel0  ($signed(check_window0)),
        .pixel1  ($signed(check_window1)),
        .pixel2  ($signed(check_window2)),
        .pixel3  ($signed(check_window3)),
        .pixel4  ($signed(check_window4)),
        .pixel5  ($signed(check_window5)),
        .pixel6  ($signed(check_window6)),
        .pixel7  ($signed(check_window7)),
        .pixel8  ($signed(check_window8)),

        .kernel0 (kernel0),
        .kernel1 (kernel1),
        .kernel2 (kernel2),
        .kernel3 (kernel3),
        .kernel4 (kernel4),
        .kernel5 (kernel5),
        .kernel6 (kernel6),
        .kernel7 (kernel7),
        .kernel8 (kernel8),

        .result        (mac_result),
        .residue_error (residue_check_result)
    );

    // ============================================================
    // OUTPUT REGISTER
    // ============================================================

    always_ff @(posedge clk) begin

        if (rst) begin

            result        <= 20'sd0;
            result_valid  <= 1'b0;
            residue_error <= 1'b0;

        end

        else begin

            // ----------------------------------------------------
            // Valid output only when both window generators
            // indicate a valid window.
            // ----------------------------------------------------

            result_valid <= window_valid &
                            check_window_valid;

            // ----------------------------------------------------
            // Main result
            // ----------------------------------------------------

            if (window_valid &&
                check_window_valid) begin

                result <= mac_result;

                residue_error <= residue_check_result;

            end

            else begin

                residue_error <= 1'b0;

            end

        end

    end

endmodule